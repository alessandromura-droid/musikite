#!/usr/bin/env python3
"""
Build the SYSTEM exercise library of the app (owner, 2026-11-19) from a folder of MIDI
files: the folder musikite/data/library/ (index.json + mid/<file>.mid, one small MIDI per
melody).

    python3 scripts/build_library.py FOLDER --none --modal
    python3 scripts/build_library.py FOLDER --inversion --inversion-modal --out /tmp/library

WHICH MELODIES (at least one flag; owner, 2026-11-19: "the allowed transformations"):
  --none                  the source MIDI itself, COPIED UNCHANGED (byte for byte)
  --modal                 the melody in the 6 other church modes (same tonic)
  --inversion             mirror around the tonic, in its own mode
  --inversion-modal       the mirror in the 6 other modes
  --retrograde            the melody backwards
  --retrograde-modal      the retrograde in the 6 other modes
  --retrograde-inversion  retrograde of the mirror
  --crossings N           at most N CROSSED melodies (pitches of one on the rhythm of another
                          with the same metre, pairs at random; default 0)
  --generated N           N melodies GENERATED by a Markov model of the sources (default 0)
  --min-entropy X         melodies under X bits are thrown away (default 3.5; 0 = no filter)
  --seed S                same seed + same files = the same library (default 2026)
The old settings: "inversion" = --inversion --inversion-modal (7 per source); "all" =
--retrograde --inversion --retrograde-inversion --retrograde-modal --inversion-modal (15).

THE FILES WRITTEN (owner: "clarity on the destination files"): the melody of a source
"Matteo Carcassi - I 07 Waltz.mid" is
  mid/Matteo Carcassi - I 07 Waltz.mid                          --none (identical copy)
  mid/Matteo Carcassi - I 07 Waltz - dorian.mid                 --modal (also phrygian…)
  mid/Matteo Carcassi - I 07 Waltz - inversion.mid              --inversion
  mid/Matteo Carcassi - I 07 Waltz - inversion, dorian.mid      --inversion-modal
  mid/Matteo Carcassi - I 07 Waltz - retrograde.mid             --retrograde
  mid/Matteo Carcassi - I 07 Waltz - retrograde, dorian.mid     --retrograde-modal
  mid/Matteo Carcassi - I 07 Waltz - retrograde inversion.mid   --retrograde-inversion
and the same name is its TITLE in the app; the mode in the name is the one APPLIED (the key
written in the index is estimated again on the result). Crossed and generated melodies:
"Melody <n>", file mid/<id>.mid. Every melody except --none is one voice (the part with the
most notes, top note of chords). --none is an exception to the rule "the sources never go
into the library", chosen by the owner (2026-11-19): use it only with files you may
distribute.

Every source must have at least 16 notes and pass the entropy filter (else skipped, with the
reason); every result too.

ADDITIVE (owner, 2026-11-19: the library can be built from different sources, one run per
folder): the melodies already in the output folder stay as they are (file, index entry,
number); nothing is removed; a melody with the same id (its notes AND its name) as one
already there is not added again, so running the same folder twice adds nothing; new
melodies get the numbers after the highest one. To start a library from scratch, empty
the output folder by hand first.

What it changes: only the output folder: it ADDS the MIDI of every new melody and rewrites
index.json with the old entries plus the new ones; the source MIDI files are only read. Time: about
a second per source file (music21) plus the difficulty of every melody: minutes to tens of
minutes for a few hundred files.
"""
import argparse
import math
import os
import random
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
PROJECT = os.path.dirname(HERE)
sys.path.insert(0, PROJECT)

FLAGS = ("none", "modal", "inversion", "inversion-modal", "retrograde", "retrograde-modal",
         "retrograde-inversion")


def original(data, src, title):
    """The melody of a source MIDI read EXACTLY as the app will read the copied file
    (library.melody_from_midi_bytes), so that its index entry describes that file."""
    from musikite.library import melody_from_midi_bytes
    from musikite.theory import key_of_notes
    entry = dict(bpm=float(src.practice_bpm or src.bpm), ts=list(src.ts), bars=1, tonic=0,
                 mode="ionian", title=title)
    ph = melody_from_midi_bytes(data, entry)
    if not ph.notes:
        return None
    end = max(s + d for s, d, _ in ph.notes)
    ph.bars = max(1, int(math.ceil(end / ph.bar_q - 1e-9)))
    ph.tonic, ph.mode = key_of_notes(ph.notes)
    return ph


def main(argv=None):
    from musikite.library import SYSTEM_DIR, write_library
    from musikite import libgen
    from musikite.midi import Midi
    ap = argparse.ArgumentParser(description="Build the exercise library from a folder of MIDI files")
    ap.add_argument("folder", help="folder with the MIDI files (no subfolders)")
    ap.add_argument("--out", default=SYSTEM_DIR, help="library folder (default: the package's)")
    for f in FLAGS:
        ap.add_argument(f"--{f}", action="store_true")
    ap.add_argument("--crossings", type=int, default=0, help="crossed melodies, at most")
    ap.add_argument("--generated", type=int, default=0, help="melodies generated (Markov)")
    ap.add_argument("--min-entropy", type=float, default=3.5, help="bits; 0 = no filter")
    ap.add_argument("--seed", type=int, default=2026)
    a = ap.parse_args(argv)
    chosen = [f for f in FLAGS if getattr(a, f.replace("-", "_"))]
    if not chosen and not a.crossings and not a.generated:
        ap.error("choose at least one of " + ", ".join("--" + f for f in FLAGS))
    print("transformations: " + (", ".join(chosen) or "none chosen")
          + f"; crossings {a.crossings}, generated {a.generated}, min entropy {a.min_entropy}")
    t0 = time.time()
    rng = random.Random(a.seed)
    files = sorted(f for f in os.listdir(a.folder)
                   if f.lower().endswith((".mid", ".midi")) and not f.startswith("._")
                   and os.path.isfile(os.path.join(a.folder, f)))
    if not files:
        sys.exit(f"no MIDI files in {a.folder}")

    items, sources, made = [], [], []
    others = [f for f in chosen if f != "none"]
    for f in files:
        path = os.path.join(a.folder, f)
        stem = os.path.splitext(f)[0]
        try:
            src = libgen.melody_of_midi(Midi(path), stem)
        except Exception as e:
            print(f"{f}: skipped ({type(e).__name__}: {e})")
            continue
        if src is None:
            print(f"{f}: skipped (no part with {libgen.MIN_NOTES} notes)")
            continue
        h = libgen.entropy(src)
        if not libgen.passes(src, a.min_entropy):
            print(f"{f}: skipped (entropy {h:.2f} < {a.min_entropy}, {len(src.notes)} notes)")
            continue
        sources.append(src)
        tags = []
        if "none" in chosen:
            with open(path, "rb") as fh:
                data = fh.read()
            ph = original(data, src, stem)
            if ph is not None:
                items.append(("original", ph, stem, data))
                made.append(ph)
                tags.append("none")
        if others:
            for tag, p in libgen.transformations(src, others):
                if libgen.passes(p, a.min_entropy):
                    p.title = f"{stem} - {tag}"
                    items.append(("transformed", p, p.title))
                    made.append(p)
                    tags.append(tag)
        print(f"{f}: {len(src.notes)} notes, {src.bars} bars, entropy {h:.2f} -> "
              f"{len(tags)} melodies ({', '.join(tags)})")
    print(f"{len(sources)} sources of {len(files)} files, {len(items)} melodies made from them")
    crossed = libgen.crossings(made, a.crossings, a.min_entropy, rng) if a.crossings else []
    generated = (libgen.generate(sources, a.generated, a.min_entropy, rng)
                 if a.generated else [])
    print(f"{len(crossed)} crossed, {len(generated)} generated melodies")
    items += [("crossed", p) for p in crossed] + [("generated", p) for p in generated]
    added, total = write_library(items, a.out)
    print(f"{added} melodies added ({len(items) - added} already there), {total} in "
          f"{a.out} ({time.time() - t0:.0f} s)")


if __name__ == "__main__":
    main()
