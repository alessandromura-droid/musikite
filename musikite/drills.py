def settings_of(kind, saved=None):
    s = dict(DEFAULTS[kind])
    s.update({k: v for k, v in (saved or {}).items() if k in s})
    return s


def _key(kind, content):
    h = hashlib.sha1(json.dumps(content, sort_keys=True).encode()).hexdigest()[:12]
    return f"{kind}:{h}"


class Drill:
    """One generated exercise: kind, title, key (identity for the diary), phrase."""

    def __init__(self, kind, phrase, key, title, info=None):
        self.kind, self.phrase, self.key, self.title = kind, phrase, key, title
        self.info = dict(info or {})

    def __repr__(self):
        return f"Drill({self.kind}, '{self.title}')"

    def to_dict(self):
        return dict(kind=self.kind, key=self.key, title=self.title, info=self.info,
                    phrase=self.phrase.to_dict())

    @classmethod
    def from_dict(cls, d):
        return cls(d["kind"], Phrase.from_dict(d["phrase"]), d["key"], d["title"], d.get("info"))

    # ---------------------------------------------------------- take
    def check(self, bpm=None, click_mode="normal", click_gain=1.0, user=None, click=True):
        """PlayCheck of one take (count-in bar + clicks + recording). click=False: the
        clicks start silent (PlayCheck.set_click switches them during the take)."""
        from .playcheck import PlayCheck, chord_audio
        ph = self.phrase
        bpm = float(bpm or ph.bpm)
        backing = None
        if self.kind == "chord_arpeggios":     # the chords, each at its first click
            T = ph.transposition
            backing = chord_audio([(th.parse_chord(c).transpose(-T), st, du)
                                   for c, st, du in self.info["chords"]], bpm,
                                  lead_q=4.0)
        elif self.kind == "improvisation":     # the whole backing track, continuous
            backing = improvisation_audio(self.info, ph.transposition, bpm, lead_q=4.0)
        pc = PlayCheck(ph.to_score(), 0, None, bpm, ph.transposition,
                       user=user, click=click, click_mode=click_mode, click_gain=click_gain,
                       play_trasp=TRUMPET[0] if ph.program == TRUMPET[1] else None,
                       backing=backing, instrument=getattr(ph, "instrument", None),
                       detect_range=DETECT_RANGE.get(getattr(ph, "instrument", None)))
        pc.midi_written = True              # a MIDI keyboard plays the note READ
        return pc

    # ---------------------------------------------------------- evaluation
    def evaluate(self, pc, source="microphone"):
        """dict(grade, fraction, rating, colors {table row: colour}, text, detail)."""
        from .playcheck import rating
        if self.kind == "long_tones":
            r = _eval_long_tones(self, pc)
        elif self.kind in CHORD_KINDS:
            r = _eval_chords(self, pc, source)
        elif self.kind == "rhythm":
            r = _eval_rhythm(self, pc, source)
        else:
            r = _eval_sequence(self, pc, source)
        r["rating"] = rating(r["fraction"])
        r["grade"] = round(10.0 * r["fraction"], 1)
        return r

    def record(self, r, pc, user=None):
        """Practice diary: one attempt (study time = twice the take)."""
        from .diary import get, SOUND_FACTOR
        return get(user).record(self.kind, self.key, r["grade"],
                                SOUND_FACTOR * float(getattr(pc, "duration", 0.0) or 0.0),
                                self.title)


