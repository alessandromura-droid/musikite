def _expected(pc):
    """(table row, event) of the notes of the take (rests skipped)."""
    return [(i, e) for i, e in enumerate(pc.events) if e["pitch"] is not None]


def _played_written(pc, source):
    """Notes played [start_q, dur_q, written] (count-in removed), from the microphone
    or the MIDI keyboard."""
    import numpy as np
    from .transcribe import audio_notes, to_quarters
    if source == "midi":
        for n, t0 in list(getattr(pc, "_open", {}).items()):
            pc.midi_played.append([t0, 0.2, n])
        pc._open = {}
        off = 0 if pc.midi_written else pc.trasp
        return [[s, d, p + off] for s, d, p in
                to_quarters(sorted(pc.midi_played), pc.bpm, 0.0, pc.lead_q)], 0.0
    y = np.asarray(pc.recording, dtype=float).ravel()[pc.offset:]
    delay, _ = pc.align(y)
    y3 = y[max(0, int(round(pc.fs * delay)) - 1):]
    prof = getattr(pc, "profile", None) or {}
    if prof.get("family") == "decaying":       # piano…: by attacks; a chord = no note
        from .detect import decaying_notes, click_info
        times, ref = click_info(pc.click, pc.fs) if pc.click_mode != "none" else ([], None)
        found = decaying_notes(y3, pc.fs, prof.get("range"), times, ref)
        notes = [[s, d, p + pc.trasp] for s, d, p, chord, _ in found if not chord]
    else:
        notes = audio_notes(y3, pc.fs, pc.trasp, range_trasp=pc.play_trasp,
                            concert_range=getattr(pc, "detect_range", None))
    return to_quarters(notes, pc.bpm, 0.0, pc.lead_q), delay


def lcs_match(expected, played):
    """Indices of `expected` matched, in order, by `played` (longest common subsequence)."""
    n, m = len(expected), len(played)
    L = [[0] * (m + 1) for _ in range(n + 1)]
    for i in range(n - 1, -1, -1):
        for j in range(m - 1, -1, -1):
            L[i][j] = L[i + 1][j + 1] + 1 if expected[i] == played[j] else max(L[i + 1][j], L[i][j + 1])
    out, i, j = set(), 0, 0
    while i < n and j < m:
        if expected[i] == played[j]:
            out.add(i)
            i += 1
            j += 1
        elif L[i + 1][j] >= L[i][j + 1]:
            i += 1
        else:
            j += 1
    return out


def _eval_sequence(d, pc, source):
    exp = _expected(pc)
    end_q = max(e["start"] + e["dur"] for _, e in exp) + 2.0
    played, delay = _played_written(pc, source)
    seq = []
    for s, du, p in sorted(played):
        if s + du <= -0.25 or s > end_q:              # count-in noise, after the end
            continue
        if not seq or seq[-1] != p:                    # repetitions of a held note merged
            seq.append(p)
    groups = []                        # a note tied over the bar line = ONE note (lip slurs)
    for row, e in exp:
        g = groups[-1] if groups else None
        if g and g["pitch"] == e["pitch"] and abs(g["end"] - e["start"]) < 1e-6:
            g["rows"].append(row)
            g["end"] = e["start"] + e["dur"]
        else:
            groups.append(dict(pitch=e["pitch"], end=e["start"] + e["dur"], rows=[row]))
    ok = lcs_match([g["pitch"] for g in groups], seq)
    colors = {row: ("green" if k in ok else "red")
              for k, g in enumerate(groups) for row in g["rows"]}
    frac = len(ok) / len(groups) if groups else 0.0
    names = " ".join(th.note_name(p) for p in seq) or "nothing"
    return dict(fraction=frac, colors=colors,
                text=f"{len(ok)}/{len(groups)} notes in the right order",
                detail=dict(played=seq, played_names=names, delay=delay))


def _held_notes(pc):
    """Notes of the take with the tied parts joined: [(rows, start, dur, pitch)]."""
    out = []
    for row, e in _expected(pc):
        if out and out[-1][3] == e["pitch"] and abs(out[-1][1] + out[-1][2] - e["start"]) < 1e-6:
            rows, st, du, p = out[-1]
            out[-1] = (rows + [row], st, du + e["dur"], p)
        else:
            out.append(([row], e["start"], e["dur"], e["pitch"]))
    return out


def _eval_long_tones(d, pc):
    import numpy as np
    exp = [(rows, dict(start=st, dur=du, pitch=p)) for rows, st, du, p in _held_notes(pc)]
    y = np.asarray(pc.recording, dtype=float).ravel()[pc.offset:]
    delay, _ = pc.align(y)
    y3 = y[max(0, int(round(pc.fs * delay)) - 1):]
    spb = 60.0 / pc.bpm
    notes, colors, scores = [], {}, []
    for row, e in exp:
        a = (pc.lead_q + e["start"]) * spb
        b = a + e["dur"] * spb
        curve = cents_curve(y3[int(a * pc.fs):int(b * pc.fs)], pc.fs, e["pitch"] - pc.trasp)
        on = [c for _, c in curve if c is not None and abs(c) <= 50]
        seen = [c for _, c in curve if c is not None]        # also far from the note (±150)
        frames = max(1, len(curve))
        held = len(on) / frames
        mean = float(np.mean(on)) if on else None
        std = float(np.std(on)) if len(on) > 1 else None
        stab = 1.0 if std is None or std <= 8 else max(0.3, 1.0 - 0.7 * (std - 8) / 27.0)
        into = 1.0 if mean is None or abs(mean) <= 10 else max(0.5, 1.0 - 0.5 * (abs(mean) - 10) / 30.0)
        sc = held * stab * into if on else 0.0
        scores.append(sc)
        for r_ in row:
            colors[r_] = "green" if sc >= 0.6 else "red"
        notes.append(dict(pitch=e["pitch"], name=th.note_name(e["pitch"]), held=round(held, 2),
                          mean_cents=None if mean is None else round(mean, 1),
                          std_cents=None if std is None else round(std, 1),
                          off_cents=None if on or not seen else round(float(np.median(seen))),
                          score=round(sc, 2), curve=curve))
    frac = sum(scores) / len(scores) if scores else 0.0
    lines = []
    for n in notes:
        if n["mean_cents"] is None and n.get("off_cents") is not None:
            lines.append(f"{n['name']}: out of tune, {n['off_cents']:+d} c")
        elif n["mean_cents"] is None:
            lines.append(f"{n['name']}: not heard")
        else:
            lines.append(f"{n['name']}: held {100 * n['held']:.0f}%, {n['mean_cents']:+.0f} c "
                         f"± {n['std_cents'] or 0:.0f} c")
    return dict(fraction=frac, colors=colors, text="   ".join(lines),
                detail=dict(notes=notes, delay=delay))


CENTS_SEARCH = 150      # cents searched around the expected note (owner, 2026-11-09: it was
                        # 60, a missed note did not appear in the chart); the grade still
                        # counts only the frames within 50 cents (held)


def cents_curve(seg, fs, concert_pitch, frame=4096, hop=1024, search=CENTS_SEARCH):
    """[(time s, cents or None)] of a note: frequency of the strongest of the first four
    harmonics near the expected ones (±search cents, parabolic interpolation) divided by
    its number, against the expected concert pitch; None = silence / another pitch."""
    import numpy as np
    out = []
    if len(seg) < frame:
        return out
    f0 = 440.0 * 2 ** ((concert_pitch - 69) / 12.0)
    nfft = 16384
    win = np.hanning(frame)
    thr = 1e-4 * float(np.max(seg ** 2)) * frame
    freqs = np.fft.rfftfreq(nfft, 1.0 / fs)
    for i in range(0, len(seg) - frame + 1, hop):
        x = seg[i:i + frame] * win
        if float(np.sum(x ** 2)) < thr:
            out.append((i / fs, None))
            continue
        X = np.abs(np.fft.rfft(x, nfft))
        top = float(X.max()) or 1.0
        best = None
        for h in (1, 2, 3, 4):
            fh = f0 * h
            band = (freqs > fh * 2 ** (-search / 1200)) & (freqs < fh * 2 ** (search / 1200))
            if not band.any():
                continue
            k = np.flatnonzero(band)[np.argmax(X[band])]
            if X[k] < 0.2 * top or k <= 0 or k >= len(X) - 1:
                continue
            a, b, c = X[k - 1], X[k], X[k + 1]
            dk = 0.5 * (a - c) / (a - 2 * b + c) if (a - 2 * b + c) != 0 else 0.0
            f = (k + dk) * fs / nfft / h
            if best is None or X[k] > best[1]:
                best = (f, X[k])
        out.append((i / fs, None if best is None else 1200.0 * np.log2(best[0] / f0)))
    return out


CLAP_SENSITIVITY = (0.25, 0.18, 0.12, 0.08, 0.05)   # peak height / strongest clap, tried in order


def clap_strength(y, fs, notch_hz=None):
    """Onset strength of claps (rise of the high-passed energy, every 5 ms) after removing
    the 'high' click with a notch filter (notch_hz). Returns (strength, seconds per value)."""
    import numpy as np
    from scipy.signal import butter, sosfiltfilt, iirnotch, filtfilt
    y = np.asarray(y, dtype=float).ravel()
    if len(y) < fs // 10:
        return np.zeros(0), 0.005
    if notch_hz:
        for q in (8.0, 8.0):                       # twice: deep enough for the clicks
            b, a = iirnotch(notch_hz, q, fs)
            y = filtfilt(b, a, y)
    sos = butter(4, 300.0, "highpass", fs=fs, output="sos")
    y = sosfiltfilt(sos, y)
    hop = int(0.005 * fs)
    env = np.sqrt(np.convolve(y ** 2, np.ones(hop) / hop, mode="same"))[::hop]
    if not len(env) or env.max() <= 0:
        return np.zeros(0), 0.005
    return np.maximum(0.0, np.diff(env, prepend=env[0])), hop / fs


def clap_peaks(strength, dt, rel=0.25, min_gap=0.06):
    """Times (s) of the peaks of the onset strength higher than rel × the strongest."""
    from scipy.signal import find_peaks
    if not len(strength) or strength.max() <= 0:
        return []
    p, _ = find_peaks(strength, height=rel * strength.max(), distance=max(1, int(min_gap / dt)))
    return [float(k * dt) for k in p]


def clap_onsets(y, fs, notch_hz=None, min_gap=0.06, rel=0.25):
    """Times (s) of the claps in a recording (see clap_strength, clap_peaks)."""
    st, dt = clap_strength(y, fs, notch_hz)
    return clap_peaks(st, dt, rel, min_gap)


def _match_onsets(exp, on_q, tol=None):
    """Claps paired one to one with the written notes (closest first, at most tol)."""
    tol = RHYTHM_TOL_Q if tol is None else tol
    pairs = sorted((abs(q - e["start"]), k, j) for k, (_, e) in enumerate(exp)
                   for j, q in enumerate(on_q) if abs(q - e["start"]) <= tol)
    match, used = {}, set()
    for dt, k, j in pairs:
        if k not in match and j not in used:
            match[k] = (j, on_q[j] - exp[k][1]["start"])
            used.add(j)
    return match, len(on_q) - len(used)


def _eval_rhythm(d, pc, source):
    """Microphone: soft claps escape a fixed threshold (owner: "be lenient, claps get
    lost"), so the take (kept in memory) is analysed again at higher sensitivities
    (CLAP_SENSITIVITY) and the most sensitive one is kept as long as it finds MORE notes
    without adding claps far from every written note (those would be noise, not claps:
    a grade is never raised by noise)."""
    import numpy as np
    exp = _expected(pc)
    spb = 60.0 / pc.bpm
    end_q = max(e["start"] + e["dur"] for _, e in exp) + 1.0
    sens = None
    if source in ("key", "midi"):                      # taps: space bar or any MIDI key
        on_q = sorted(t / spb - pc.lead_q for t in pc.taps)
        on_q = [q for q in on_q if -RHYTHM_TOL_Q <= q <= end_q]
        match, extra = _match_onsets(exp, on_q)
        delay = 0.0
    else:
        y = np.asarray(pc.recording, dtype=float).ravel()[pc.offset:]
        delay, _ = pc.align(y)
        y3 = y[max(0, int(round(pc.fs * delay)) - 1):]
        notch = 4000.0 if getattr(pc, "click_mode", "") == "high" else None
        st, dt = clap_strength(y3, pc.fs, notch)
        best = None
        for rel in CLAP_SENSITIVITY:
            q = [t / spb - pc.lead_q for t in clap_peaks(st, dt, rel)]
            q = [x for x in q if -RHYTHM_TOL_Q <= x <= end_q]
            m, ex = _match_onsets(exp, q)
            far = sum(1 for x in q if all(abs(x - e["start"]) > 2 * RHYTHM_TOL_Q for _, e in exp))
            if best is None:
                best = (rel, q, m, ex, far)
            elif len(m) > len(best[2]) and far <= best[4]:
                best = (rel, q, m, ex, far)
        sens, on_q, match, extra, _ = best
    ok = len(match)
    frac = max(0.0, (ok - 0.5 * extra) / len(exp)) if exp else 0.0
    colors = {row: ("green" if k in match else "red") for k, (row, _) in enumerate(exp)}
    errs = [abs(v[1]) * spb * 1000 for v in match.values()]
    mean_ms = float(np.mean(errs)) if errs else None
    text = f"{ok}/{len(exp)} on time" + (f", {extra} extra" if extra else "") + \
        (f", mean error {mean_ms:.0f} ms" if mean_ms is not None else "")
    return dict(fraction=min(1.0, frac), colors=colors, text=text,
                detail=dict(onsets_q=[round(q, 3) for q in on_q], extra=extra,
                            mean_error_ms=mean_ms, delay=delay, sensitivity=sens))


# ---------------------------------------------------------------- chord arpeggios
def _minor_progression(name):
    """A progression is in a minor key when one of its chords is the lower-case i."""
    from .progressions import CATALOGUE
    roman = CATALOGUE.get(name, {}).get("roman", name)
    return any(re.match(r"^i(?![iv])", t.split("/")[0]) for bar in roman.split()
               for t in bar.split(":"))


def chord_voicing(chord):
    """CONCERT pitches the piano plays for a chord (concert Chord): root in octave 2, the
    chord tones folded into the octave C3-B3 (low: the range of the player stays free)."""
    from .playcheck import CHORD_ROOT_LO, CHORD_VOICING_LO
    root = CHORD_ROOT_LO + (chord.root - CHORD_ROOT_LO) % 12
    return sorted({root} | {CHORD_VOICING_LO + (pc - CHORD_VOICING_LO) % 12
                            for pc in chord.pcs})


def chord_context(chords, key, minor=False):
    """[(Chord, ctx)] of written chord symbols: ctx = key, previous, next (theory.RULES)."""
    cs = [th.parse_chord(c) for c in chords]
    k = th.Key(key, "aeolian" if minor else "ionian")
    return [(c, dict(key=k, prev=cs[i - 1] if i else None,
                     next=cs[i + 1] if i + 1 < len(cs) else None)) for i, c in enumerate(cs)]


def chord_notes(chord, ctx):
    """(chord tones, tensions): pitch classes of the right notes on a chord in context."""
    tones = sorted(chord.pcs, key=lambda pc: (pc - chord.root) % 12)
    tens = [pc for pc in ((chord.root + i) % 12 for i in range(12))
            if pc not in chord.pcs and th.RULES.classify(pc, chord, **ctx) == "tension"]
    return tones, tens


def _chord_arpeggios(s, rng):
    from .progressions import progression, CATALOGUE
    rand = bool(s.get("random"))
    # random: the standards' full changes are left out (long: choose them by name)
    name = rng.choice([n for n, r in CATALOGUE.items() if r.get("style") != "standard"]) \
        if rand else s["progression"]
    if name not in CATALOGUE:
        raise ValueError(f"unknown progression: {name}")
    key = rng.choice(KEYS) if rand else (s["key"] if s["key"] in KEYS else "C")
    instr, T, program, part_i, played = _instrument(s)
    clicks = rng.choice(CHORD_CLICKS) if rand else \
        (int(s["clicks"]) if int(s["clicks"]) in CHORD_CLICKS else 4)
    times = max(1, int(s["times"]))
    help_ = bool(s["help"])
    one = [c for bar in progression(name, key).split() for c in bar.split(":")]
    symbols = one * times
    chords, notes = [], []
    for i, c in enumerate(symbols):            # WRITTEN chord, its tones on the staff
        st = float(i * clicks)
        chords.append((c, st, float(clicks)))
        for p in th.parse_chord(c).voicing(58):
            notes.append([st, float(clicks), p])
    minor = _minor_progression(name)
    title = (f"{name} in {key}{' minor' if minor else ''}, {clicks} clicks a chord"
             + (f", {times} times" if times > 1 else "") + (", notes shown" if help_ else ""))
    ph = _phrase(notes, (4, 4), T, program, s["bpm"], title, th.pc_of(key),
                 "aeolian" if minor else "ionian", part=part_i)
    ph.instrument = played
    return Drill("chord_arpeggios", ph,
                 _key("chord_arpeggios", [name, key, instr, clicks, times, help_]), title,
                 dict(progression=name, key=key, minor=minor, instrument=instr, clicks=clicks,
                      times=times, help=help_, random=rand, chords=chords))


def _eval_chords(d, pc, source):
    """Notes played on every chord (onset inside it, repetitions merged), classified by
    pitch class in context; chord score = coverage × accuracy (see the module doc)."""
    info = d.info
    chords = info["chords"]
    ctxs = chord_context([c for c, _, _ in chords], info["key"], info.get("minor", False))
    played, delay = _played_written(pc, source)
    T = d.phrase.transposition
    end_q = chords[-1][1] + chords[-1][2]
    seq = []
    for s, du, p in sorted(played):
        if s < -CHORD_EARLY_Q or s >= end_q - CHORD_EARLY_Q:
            continue
        if not seq or seq[-1][1] != p:
            seq.append((s, p))
    exp = _expected(pc)
    per, colors, total = [], {}, 0.0
    for k, (c, st, du) in enumerate(chords):
        chord, ctx = ctxs[k]
        a = st - CHORD_EARLY_Q if k else -CHORD_EARLY_Q
        mine = [p for s, p in seq if a <= s < st + du - CHORD_EARLY_Q]
        if source != "midi" and d.kind == "chord_arpeggios":
            # the piano's own notes in the microphone: not counted (improvisation: the
            # backing is continuous, headphones are needed, nothing is removed)
            heard = {p + T for p in chord_voicing(chord.transpose(-T))}
            mine = [p for p in mine if p not in heard]
        right = [p for p in mine if th.RULES.classify(p, chord, **ctx) in CHORD_RIGHT]
        wrong = [p for p in mine if p not in right]
        cover = min(1.0, len({p % 12 for p in right}) / max(1, len(chord.pcs)))
        acc = len(right) / len(mine) if mine else 0.0
        sc = cover * acc
        total += sc
        per.append(dict(chord=c, score=round(sc, 3), right=len(right), wrong=len(wrong),
                        played=" ".join(th.note_name(p) for p in mine)))
        for row, e in exp:
            if st - 1e-6 <= e["start"] < st + du - 1e-6:
                colors[row] = "green" if sc >= CHORD_OK else "red"
    frac = total / len(chords) if chords else 0.0
    nr = sum(x["right"] for x in per)
    nw = sum(x["wrong"] for x in per)
    good = sum(1 for x in per if x["score"] >= CHORD_OK)
    names = " ".join(th.note_name(p) for _, p in seq) or "nothing"
    return dict(fraction=frac, colors=colors,
                text=f"{good}/{len(chords)} chords good; {nr} right notes, {nw} wrong",
                detail=dict(chords=per, played_names=names, delay=delay))


# ---------------------------------------------------------------- improvisation
def _progression_chords(name, key):
    """[(written symbol, beats)] of one pass of a progression: one bar of 4 beats per
    chord, 'A:B' = two chords of 2 beats."""
    from .progressions import progression
    out = []
    for bar in progression(name, key).split():
        parts = bar.split(":")
        for c in parts:
            out.append((c, 4.0 / len(parts)))
    return out


def _improvisation(s, rng):
    from .progressions import CATALOGUE
    from .backing import STYLES, CHORD_SOUNDS
    rand = bool(s.get("random"))
    name = rng.choice([n for n, r in CATALOGUE.items() if r.get("style") != "standard"]) \
        if rand else s["progression"]
    if name not in CATALOGUE:
        raise ValueError(f"unknown progression: {name}")
    key = rng.choice(KEYS) if rand else (s["key"] if s["key"] in KEYS else "C")
    style = s.get("style") if s.get("style") in STYLES else "swing"
    sound = s.get("sound") if s.get("sound") in CHORD_SOUNDS else "piano"
    instr, T, program, part_i, played = _instrument(s)
    lo, hi = IMPRO_CHORUSES
    choruses = max(lo, min(hi, int(s.get("choruses", 2))))
    help_ = bool(s.get("help", True))
    one = _progression_chords(name, key)
    chords, notes, t = [], [], 0.0
    for _ in range(choruses):
        for c, beats in one:
            chords.append((c, t, float(beats)))
            for p in th.parse_chord(c).voicing(58):
                notes.append([t, float(beats), p])
            t += beats
    minor = _minor_progression(name)
    title = (f"Improvise: {name} in {key}{' minor' if minor else ''}, {style}, "
             f"{choruses} chorus{'es' if choruses > 1 else ''}"
             + (", notes shown" if help_ else ""))
    ph = _phrase(notes, (4, 4), T, program, s["bpm"], title, th.pc_of(key),
                 "aeolian" if minor else "ionian", part=part_i)
    ph.instrument = played
    seed = rng.randrange(1 << 30)
    return Drill("improvisation", ph,
                 _key("improvisation", [name, key, instr, style, choruses, help_]), title,
                 dict(progression=name, key=key, minor=minor, instrument=instr, style=style,
                      sound=sound, choruses=choruses, help=help_, random=rand,
                      chords=chords, one=[c for c, _ in one], seed=seed))


def improvisation_audio(info, T, bpm, lead_q=4.0, fs=None, sf2=None, gain=0.5):
    """The backing track of an improvisation take: CONCERT chords (written - T), style,
    choruses; float array at fs, sample 0 = the first count-in click (the backing starts
    after the count-in of lead_q quarters; its own count-in and ending are left out)."""
    import numpy as np
    from .playcheck import FS
    from .backing import make_backing
    from .progressions import progression, KEYS_MAJOR
    fs = fs or FS
    if sf2 is None:
        from .midi import Midi
        sf2 = Midi._default_sf2
    if not sf2:
        raise RuntimeError("no soundfont: the backing track needs one (Settings > Soundfont)")
    concert_key = KEYS_MAJOR[(th.pc_of(info["key"]) - int(T)) % 12]
    chords = progression(info["progression"], concert_key)
    pm, _ = make_backing(chords, info.get("style", "swing"), bpm, int(info.get("choruses", 1)),
                         info.get("sound", "piano"), None, info.get("seed"), count_in=False,
                         ending=False)
    y = pm.fluidsynth(fs=fs, sf2_path=sf2)
    if y is None or not len(y):
        raise RuntimeError("the backing track could not be rendered")
    y = gain * y / max(1e-9, float(np.max(np.abs(y))))
    lead = np.zeros(int(round(lead_q * 60.0 / float(bpm) * fs)))
    return np.concatenate([lead, y]).astype(np.float32)
