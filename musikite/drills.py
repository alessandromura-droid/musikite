def make(kind, settings=None, seed=None):
    """One new exercise of a kind with the settings of the tab (missing = DEFAULTS)."""
    rng = random.Random(seed)
    s = settings_of(kind, settings)
    return {"long_tones": _long_tones, "scales": _scales, "lip_slurs": _lip_slurs,
            "rhythm": _rhythm, "chord_arpeggios": _chord_arpeggios,
            "improvisation": _improvisation}[kind](s, rng)


def _phrase(notes_w, ts, T, program, bpm, title, tonic_w=0, mode="ionian", part="",
            end_q=None, ts_changes=None):
    """Phrase from WRITTEN notes [start_q, dur_q, written] (stored at concert pitch);
    end_q: the end when the phrase finishes with a rest."""
    bar_q = ts[0] * 4.0 / ts[1]
    end = max([s + d for s, d, _ in notes_w] + [end_q or 0.0])
    bars = max(1, int(-(-end // bar_q)))
    concert = [[s, d, p - T] for s, d, p in notes_w]
    ph = Phrase(concert, bars, ts, (tonic_w - T) % 12, mode, bpm, program, part, title,
                transposition=T, purpose="drill", ts_changes=ts_changes)
    return ph


def _range(s, instrument="Bb (trumpet)"):
    lo, hi = instrument_range(instrument)
    lo = int(s.get("lowest") or lo)
    hi = int(s.get("highest") or hi)
    return min(lo, hi), max(lo, hi)


def _long_tones(s, rng):
    key, T, program, part, played = _instrument(s)
    lo, hi = _range(s, key)
    n = max(1, int(s["notes"]))
    beats, rest = float(s["beats"]), float(s["rest"])
    pool = list(range(lo, hi + 1))
    pitches = []
    while len(pitches) < n:
        p = rng.choice(pool)
        if not pitches or p != pitches[-1]:
            pitches.append(p)
    notes, t = [], 0.0
    slot = 4.0 * -(-(beats + rest) // 4.0)          # every note starts on a bar line
    for p in pitches:
        notes.append([t, beats, p])
        t += slot
    names = " ".join(th.note_name(p) for p in pitches)
    title = f"Long tones: {names} ({beats:g} beats)"
    ph = _phrase(notes, (4, 4), T, program, s["bpm"], title, part=part)
    ph.instrument = played
    content = [pitches, beats] if key == "Bb (trumpet)" else [pitches, beats, key]
    return Drill("long_tones", ph, _key("long_tones", content), title,
                 dict(pitches=pitches, beats=beats))


def scale_notes(tonic_w, kind, octaves, lo, hi):
    """Written pitches of a scale / arpeggio up and down, inside [lo, hi] (or None)."""
    up, down, _ = SCALE_TYPES[kind]

    def degrees(spec):
        return list(th.scale_pcs(0, spec)) if isinstance(spec, str) else list(spec)
    du = sorted(set(int(x) % 12 for x in degrees(up)))
    dd = sorted(set(int(x) % 12 for x in degrees(down))) if down else du
    for base in range(lo - lo % 12 + tonic_w % 12 - 12, hi + 1, 12):
        top = base + 12 * octaves
        if base < lo or top > hi:
            continue
        asc = [base + 12 * o + d for o in range(octaves) for d in du] + [top]
        desc = [base + 12 * o + d for o in range(octaves) for d in dd]
        desc = sorted(desc, reverse=True)
        return asc + desc
    return None


def _dedup_adjacent(seq):
    out = []
    for p in seq:
        if not out or out[-1] != p:
            out.append(p)
    return out


def scale_sequence(tonic_w, kind, octaves, lo, hi, pattern="straight"):
    """(up_notes, down_notes) written pitches of a scale / arpeggio with a repetitive
    classical pattern ('straight', 'thirds', 'groups of 3', 'groups of 4', 'turns',
    'arpeggio & scale'), inside [lo, hi] (or None)."""
    up, down, _ = SCALE_TYPES[kind]

    def degrees(spec):
        return list(th.scale_pcs(0, spec)) if isinstance(spec, str) else list(spec)
    du = sorted(set(int(x) % 12 for x in degrees(up)))
    dd = sorted(set(int(x) % 12 for x in degrees(down))) if down else du
    found = None
    for base in range(lo - lo % 12 + tonic_w % 12 - 12, hi + 1, 12):
        top = base + 12 * octaves
        if base < lo or top > hi:
            continue
        asc = [base + 12 * o + d for o in range(octaves) for d in du] + [top]
        desc = sorted([base + 12 * o + d for o in range(octaves) for d in dd], reverse=True)
        found = (asc, desc)
        break
    if found is None:
        return None
    asc, desc = found
    if pattern == "arpeggio & scale" and len(du) != 7:     # arpeggios, chromatic: no 1-3-5
        pattern = "groups of 3"
    if pattern == "thirds" and len(asc) >= 4:
        up_seq = [p for i in range(len(asc) - 2) for p in (asc[i], asc[i + 2])] + [asc[-1]]
        dn_seq = [p for i in range(len(desc) - 2) for p in (desc[i], desc[i + 2])] + [desc[-1]]
    elif pattern == "groups of 3" and len(asc) >= 4:
        up_seq = [p for i in range(len(asc) - 2) for p in (asc[i], asc[i + 1], asc[i + 2])] + [asc[-1]]
        dn_seq = [p for i in range(len(desc) - 2) for p in (desc[i], desc[i + 1], desc[i + 2])] + [desc[-1]]
    elif pattern == "groups of 4" and len(asc) >= 5:
        up_seq = [p for i in range(len(asc) - 3) for p in asc[i:i + 4]] + [asc[-1]]
        dn_seq = [p for i in range(len(desc) - 3) for p in desc[i:i + 4]] + [desc[-1]]
    elif pattern == "turns" and len(asc) >= 3:
        up_seq = [p for i in range(len(asc) - 1) for p in (asc[i], asc[i + 1], asc[i])] + [asc[-1]]
        dn_seq = [p for i in range(len(desc) - 1) for p in (desc[i], desc[i + 1], desc[i])] + [desc[-1]]
    elif pattern == "arpeggio & scale":
        arp = [asc[o * len(du) + i] for o in range(octaves) for i in (0, 2, 4)
               if o * len(du) + i < len(asc)] + [asc[-1]]
        up_seq, dn_seq = arp, list(desc)
    else:
        up_seq, dn_seq = list(asc), list(desc)
    up_seq = _dedup_adjacent(up_seq)
    dn_seq = _dedup_adjacent(dn_seq)
    if dn_seq and up_seq and dn_seq[0] == up_seq[-1]:
        dn_seq = dn_seq[1:]
    return up_seq, dn_seq


